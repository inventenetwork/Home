const TABLES = { en: EN, ms: MS };
const LS = 'h360.lang';

let lang = (() => {
  try {
    const saved = localStorage.getItem(LS);
    if (saved === 'en' || saved === 'ms') return saved;
  } catch { /* storage blocked */ }
  return (navigator.language || 'en').toLowerCase().startsWith('ms') ? 'ms' : 'en';
})();
document.documentElement.lang = lang;

export const getLang = () => lang;
export function setLang(next) {
  if (next !== 'en' && next !== 'ms') return;
  lang = next;
  document.documentElement.lang = next;
  try { localStorage.setItem(LS, next); } catch { /* ignore */ }
}

export const hasKey = (key) => key in TABLES[lang] || key in EN;

export function t(key, vars = {}) {
  const raw = TABLES[lang][key] ?? EN[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined ? `{${k}}` : String(vars[k])));
}

const locale = () => (lang === 'ms' ? 'ms-MY' : 'en-MY');

/** 'YYYY-MM-DD' (a Malaysia calendar date) to e.g. "Wed, 21 Oct". */
export function fmtDay(dateStr, opts = { weekday: 'short', day: 'numeric', month: 'short' }) {
  return new Intl.DateTimeFormat(locale(), { ...opts, timeZone: 'UTC' }).format(new Date(`${dateStr}T12:00:00Z`));
}

export function fmtDuration(minutes) {
  const h = Math.floor(minutes / 60);
  const m = minutes % 60;
  const parts = [];
  if (h) parts.push(t(h === 1 ? 'dur.hr' : 'dur.hrs', { n: h }));
  if (m) parts.push(t('dur.min', { n: m }));
  return parts.join(' ') || t('dur.min', { n: 0 });
}
